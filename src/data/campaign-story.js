export function stageStory(ch, st) {
  const row = CHAPTER_SCENES[ch - 1]?.[st - 1];
  if (!row) throw new RangeError('존재하지 않는 이야기입니다.');
  return { title: row[0], opening: row[1], revelation: row[2], aftermath: row[3] };
}

export function journalEntries(progress = {}) {
  const stars = progress?.stars ?? {};
  const entries = [];
  for (let ch = 1; ch <= CHAPTER_SCENES.length; ch++) for (let st = 1; st <= CHAPTER_SCENES[ch - 1].length; st++) {
    const code = `${ch}-${st}`;
    if (typeof stars[code] !== 'number' || !Number.isFinite(stars[code]) || stars[code] < 1) continue;
    const scene = stageStory(ch, st);
    entries.push({ code, ch, st, title: scene.title, text: scene.aftermath, revelation: scene.revelation, aftermath: scene.aftermath });
  }
  return entries;
}
