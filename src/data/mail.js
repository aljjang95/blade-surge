/** 새 저장의 우편함(수령 전). */
export const freshMailbox = () => MAILBOX.map((m) => ({ ...m, rewards: { ...m.rewards } }));

/** 지금 보이고 받을 수 있는 우편인가. */
export const mailOpen = (m, now) => (!Number.isFinite(m?.from) || now >= m.from) && (!Number.isFinite(m?.until) || now < m.until);
